float getSOC(float voltage) {
    if (voltage <= voltage_points[0]) return 0.0f;
    if (voltage >= voltage_points[NUM_POINTS-1]) return 100.0f;
    for (int i = 0; i < NUM_POINTS-1; i++) {
        if (voltage >= voltage_points[i] && voltage <= voltage_points[i+1]) {
            float t = (voltage - voltage_points[i]) / (voltage_points[i+1] - voltage_points[i]);
            return soc_points[i] + t * (soc_points[i+1] - soc_points[i]);
        }
    }
    return 0.0f;
}

float ADC_ToBatteryVoltage(uint16_t adc)
{
    float v_adc =
        ((float)adc * ADC_REF) / ADC_MAX;

    return v_adc / DIVIDER_K;
}

float MeasureVoltage(void)
{
    uint32_t sum = 0;

    for(uint16_t i = 0; i < 256; i++)
    {
        HAL_ADC_Start(&hadc1);

        HAL_ADC_PollForConversion(&hadc1, 100);

        sum += HAL_ADC_GetValue(&hadc1);

        HAL_ADC_Stop(&hadc1);
    }

    uint16_t adc_avg = sum / 256;

    return ADC_ToBatteryVoltage(adc_avg);
}

float CalculateInternalResistance(float U1, float U2)
{
    float numerator =
        (U1 - U2) *
        R1_LOAD *
        R2_LOAD;

    float denominator =
        (U2 * R1_LOAD) -
        (U1 * R2_LOAD);

    if(fabsf(denominator) < 0.000001f)
        return -1.0f;

    return numerator / denominator;
}

float CalculateSoH(float r)
{
    float soh =
        (R0_INTERNAL / r) * 100.0f;

    if(soh > 100.0f)
        soh = 100.0f;

    if(soh < 0.0f)
        soh = 0.0f;

    return soh;
}
